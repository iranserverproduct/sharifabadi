"""Builds main.js for the public view from a dump of the workspace database.

Dump the workspace with ArtifactData into DUMP (ws_main, ws_routes and each route's current
ws_main/<id>/versions/v<ver>), then run: python3 build_view.py DUMP
"""
import json, os, sys

dump = sys.argv[1]
designs, routes = {}, []
main_dir = os.path.join(dump, 'ws_main')
for f in sorted(os.listdir(main_dir)):
    if not f.endswith('.json'):
        continue
    meta = json.load(open(os.path.join(main_dir, f), encoding='utf-8'))
    v = json.load(open(os.path.join(main_dir, f[:-5], 'versions', 'v%d.json' % meta['ver']), encoding='utf-8'))
    designs[meta['route']] = {k: v.get(k) for k in ('d', 'm', 'css', 'ver', 'title', 'by', 'at')}
routes_dir = os.path.join(dump, 'ws_routes')
if os.path.isdir(routes_dir):
    for f in sorted(os.listdir(routes_dir)):
        r = json.load(open(os.path.join(routes_dir, f), encoding='utf-8'))
        if r['path'] in designs:  # only new routes that have an approved design
            routes.append({k: r[k] for k in ('path', 'title', 'base')})
with open('main.js', 'w', encoding='utf-8') as out:
    out.write('// Approved main designs exported from the workspace. Generated by build_view.py; do not edit.\n')
    out.write('window.MAIN_DESIGNS = ' + json.dumps(designs, ensure_ascii=False) + ';\n')
    out.write('window.MAIN_ROUTES = ' + json.dumps(routes, ensure_ascii=False) + ';\n')
print(len(designs), 'designs,', len(routes), 'new routes:', ', '.join(designs))
